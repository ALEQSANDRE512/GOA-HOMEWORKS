from turtle import  *
#lets draw a house
shape("circle")
width(5)
color("red")
speed(2)
# step1: draw the square base of the house
begin_fill()
forward(200)
left(90)
forward(200)
left(90)
forward(200)
left(90)
forward(200)
left(90)
end_fill()
# step2: draw the door of the house
forward(70)
color("yellow")
begin_fill()
left(90)
forward(120)
right(90)
forward(60)
right(90)
forward(120)
right(90)
forward(60)
right(90)
end_fill()
# step3: draw roof of the house
penup()
goto(200, 200)
pendown()
color("green")
begin_fill()
right(180)
right(150)
forward(200)
right(-120)
forward(200)
end_fill()
# step4: draw windows of the house
color("blue")
penup()
goto(10, 120)
pendown()
begin_fill()
right(60)
right(180)
forward(50)
right(90)
forward(50)
right(90)
forward(50)
right(90)
forward(50)
end_fill()
penup()
goto(140, 120)
pendown()
begin_fill()
right(90)
forward(50)
right(90)
forward(50)
right(90)
forward(50)
right(90)
forward(50)
end_fill()
# the house is readdy
penup()
goto(0, 0)
color("white")
pendown()
shape("classic")
exitonclick()